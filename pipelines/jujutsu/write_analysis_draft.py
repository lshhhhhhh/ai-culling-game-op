def main():
    inv = json.loads((INVENTORY / 'inventory.json').read_text(encoding='utf-8'))
    ids = [s['id'] for s in inv['shots']]
    shots = {}
    for first, last, chars, what, hard, unit, note in G:
        for k in range(first, last + 1):
            shots[f'{k:03d}'] = dict(chars=chars, what=what, hard=hard, unit=unit, note=note)
    assert sorted(shots) == ids, set(ids) ^ set(shots)
    (INVENTORY / 'shot_analysis_draft.json').write_text(json.dumps(dict(shots=shots), ensure_ascii=False, indent=1), encoding='utf-8')
    print(len(shots), 'shots,', len(G), 'groups')


if __name__ == '__main__':
    main()
